import { GoogleGenAI } from '@google/genai';

/**
 * Formats conversation messages into the format required by Google GenAI SDK.
 * Ensures strict alternation between 'user' and 'model', starting with 'user'.
 *
 * @param {Array} messages - Previous chat messages
 * @param {string} currentMessage - The new user prompt
 * @returns {Array} - Formatted contents array
 */
function formatContents(messages = [], currentMessage) {
  const contents = [];
  let expectedRole = 'user';

  for (const msg of messages) {
    if (!msg || typeof msg.text !== 'string' || !msg.text.trim()) continue;
    const role = msg.sender === 'user' ? 'user' : 'model';

    if (role === expectedRole) {
      contents.push({
        role,
        parts: [{ text: msg.text.trim() }],
      });
      expectedRole = role === 'user' ? 'model' : 'user';
    }
  }

  // Ensure the history ends with 'model' before appending the current user message
  if (contents.length > 0 && contents[contents.length - 1].role === 'user') {
    contents.pop();
  }

  // Append current user message
  contents.push({
    role: 'user',
    parts: [{ text: currentMessage.trim() }],
  });

  return contents;
}

/**
 * Normalizes and categorizes errors from Gemini API for user-friendly feedback.
 * Distinguishes quota/rate limits, authentication, and model availability.
 *
 * @param {Error} error - The caught exception
 * @returns {Error} - Enhanced error with code and descriptive message
 */
function categorizeGeminiError(error) {
  const message = error.message || '';
  const status = error.status || (error.response && error.response.status);

  // 1. Quota / Rate-limit errors
  if (
    status === 429 ||
    error.code === 'RESOURCE_EXHAUSTED' ||
    /quota|rate.?limit|429|resource_exhausted|exhausted/i.test(message)
  ) {
    const err = new Error(
      'Gemini API quota or rate limit exceeded. You have reached the usage limit for this API key. Please check your Google AI Studio plan or try again in a few moments.'
    );
    err.status = 429;
    err.code = 'QUOTA_EXCEEDED';
    return err;
  }

  // 2. Authentication / Invalid API key
  if (
    status === 401 ||
    status === 403 ||
    /api.?key.*(invalid|not found|expired)|unauthenticated|permission_denied/i.test(message)
  ) {
    const err = new Error(
      'Invalid or unauthorized Gemini API key. Please verify your GEMINI_API_KEY in the .env file.'
    );
    err.status = status || 401;
    err.code = 'INVALID_API_KEY';
    return err;
  }

  // 3. Model not found or unsupported
  if (status === 404 || /model.*not found|unsupported model/i.test(message)) {
    const err = new Error(
      'The configured Gemini model is not accessible or not found for this API key. Please check the model name in your settings.'
    );
    err.status = 404;
    err.code = 'MODEL_NOT_FOUND';
    return err;
  }

  // 4. Temporary high demand / 503
  if (status === 503 || /high demand|unavailable|temporar/i.test(message)) {
    const err = new Error(
      'The Gemini model is currently experiencing temporary high demand on Google servers. Please try sending your message again in a few moments.'
    );
    err.status = 503;
    err.code = 'HIGH_DEMAND';
    return err;
  }

  // 5. General network / SDK error
  const err = new Error(
    message || 'An unexpected error occurred while communicating with Google Gemini API.'
  );
  err.status = status || 500;
  err.code = error.code || 'GEMINI_API_ERROR';
  return err;
}

/**
 * Generates an AI response using the official @google/genai SDK.
 * 
 * @param {string} message - Current prompt from the user
 * @param {Array} history - Previous messages in the conversation
 * @returns {Promise<string>} - Text generated by Gemini
 */
export async function generateGeminiResponse(message, history = []) {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey || apiKey.trim() === '' || apiKey === 'your_gemini_api_key_here') {
    const error = new Error(
      'Gemini API key is not configured. Please set GEMINI_API_KEY in your .env file and restart the server.'
    );
    error.status = 503;
    error.code = 'MISSING_API_KEY';
    throw error;
  }

  // Use currently supported model, defaulting to gemini-3.8-flash
  const modelName = process.env.GEMINI_MODEL || 'gemini-3.8-flash';
  const ai = new GoogleGenAI({ apiKey: apiKey.trim() });

  const contents = formatContents(history, message);

  try {
    const response = await ai.models.generateContent({
      model: modelName,
      contents,
    });

    if (!response || !response.text) {
      throw new Error('Empty response received from Gemini API.');
    }

    return response.text;
  } catch (error) {
    throw categorizeGeminiError(error);
  }
}
